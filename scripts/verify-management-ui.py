import json, os, urllib.request
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

out = Path('artifacts/management-ui')
checks, errors, history_requests = [], [], []
def check(name, value=True):
    assert value, name
    checks.append(name)
def state(path='/state'):
    with urllib.request.urlopen(os.environ['MOBILE_HERDR_TEST_INSPECTOR'] + path, timeout=5) as response:
        return json.load(response)
def shot(page, name):
    page.wait_for_function("() => document.getAnimations().filter(a=>a.effect.getComputedTiming().iterations!==Infinity).every(a=>a.playState!=='running')")
    page.screenshot(path=str(out / name))
def terminal(ws):
    ws.on_message(lambda data: ws.send('{"type":"ready"}') if json.loads(data)['type']=='auth' else None)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,record_video_dir=str(out/'video'))
    page=context.new_page();page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('request',lambda request:history_requests.append(request.url) if '/history?' in request.url else None)
    page.route_web_socket('**/api/terminal',terminal)
    page.goto(os.environ['MOBILE_HERDR_TEST_URL'])
    page.get_by_label('连接密钥',exact=True).fill(os.environ['MOBILE_HERDR_TEST_TOKEN'])
    page.get_by_label('连接开发机',exact=True).click()
    scroll=page.get_by_test_id('conversation-scroll')
    expect(page.get_by_text('管理历史消息 259 · 原来的完整对话',exact=True)).to_be_visible()
    def history_failure(route):route.fulfill(status=503,content_type='application/json',body=json.dumps({'error':{'message':'历史连接暂时中断'}}))
    page.route('**/api/panes/*/history?*',history_failure)
    scroll.evaluate('el=>el.scrollTop=0')
    expect(page.get_by_label('重试加载更早记录',exact=True)).to_be_visible()
    check('scrolling to the top loads history automatically and exposes read failures',len(history_requests)==1)
    page.unroute('**/api/panes/*/history?*',history_failure)
    anchor=page.locator('#chat-message-history-100')
    old_top=anchor.bounding_box()['y']
    page.get_by_label('重试加载更早记录',exact=True).click()
    expect(page.locator('#chat-message-history-40')).to_have_count(1)
    page.wait_for_function("() => !document.querySelector('[aria-label=\"加载更早记录\"]')?.textContent.includes('加载更早记录…')")
    check('prepending older records preserves the visible reading anchor',abs(anchor.bounding_box()['y']-old_top)<5)
    scroll.evaluate('el=>el.scrollTop=0')
    expect(page.locator('#chat-message-history-0')).to_have_count(1)
    expect(page.get_by_text('已到最早记录',exact=True)).to_have_count(1)
    check('another upward scroll reaches the first original message without a hidden menu',len(history_requests)==3)
    scroll.evaluate('el=>el.scrollTop=0')
    expect(page.get_by_text('管理历史消息 0 · 原来的完整对话',exact=True)).to_be_visible()
    expect(page.get_by_text('已到最早记录',exact=True)).to_be_visible()
    shot(page,'history-oldest.png')
    page.get_by_label('更多会话操作',exact=True).click();page.get_by_label('原生连接详情',exact=True).click()
    state('/working')
    page.get_by_label('用新版 mherdr 重启当前会话',exact=True).click()
    expect(page.get_by_text('等待当前任务完成，再用新版 mherdr 重启，可取消…',exact=True)).to_be_visible()
    shot(page,'restart-waiting.png')
    page.get_by_label('取消等待重启',exact=True).click()
    expect(page.get_by_text('已取消，当前 agent 保持运行。',exact=True)).to_be_visible()
    check('restart is one explicit action, waits for active work and can be cancelled')
    page.get_by_label('关闭原生连接详情',exact=True).click()
    page.get_by_label('打开会话列表',exact=True).click()
    page.get_by_label('新建工作区',exact=True).click()
    page.get_by_label('布局名称',exact=True).fill('手机空间')
    page.get_by_label('新终端工作目录',exact=True).fill('/tmp/project')
    shot(page,'create-workspace.png')
    page.get_by_label('提交布局操作',exact=True).click()
    expect(page.get_by_role('tab',name='终端',exact=True)).to_have_attribute('aria-selected','true')
    check('workspace creation opens its returned terminal while preserving desktop focus',state()['workspaces']==4 and state()['focused']=='w1:p1')
    page.get_by_label('打开会话列表',exact=True).click()
    page.get_by_label('新建标签页 w4',exact=True).click()
    page.get_by_label('布局名称',exact=True).fill('调试标签')
    page.get_by_label('提交布局操作',exact=True).click()
    expect(page.get_by_label('关闭布局管理',exact=True)).not_to_be_visible()
    check('new tab uses the selected workspace',state()['calls'][-1]['params']['workspace_id']=='w4')
    page.get_by_label('打开会话列表',exact=True).click();page.get_by_label('管理工作区 w4',exact=True).click()
    page.get_by_label('重命名标签页',exact=True).click()
    page.get_by_label('布局名称',exact=True).fill('重命名标签')
    page.get_by_label('提交布局操作',exact=True).click()
    expect(page.get_by_label('关闭布局管理',exact=True)).not_to_be_visible()
    check('rename targets the tab selected on the phone',state()['calls'][-1]['params']['tab_id']=='w4:t2')
    page.get_by_label('管理工作区 w4',exact=True).click();page.get_by_label('拆分终端',exact=True).click()
    for width,height in [(320,568),(390,450),(844,390)]:
        page.set_viewport_size({'width':width,'height':height})
        expect(page.get_by_label('提交布局操作',exact=True)).to_be_visible()
        check(f'{width}x{height}: layout controls fit without horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':390,'height':844})
    shot(page,'split-pane.png')
    page.get_by_label('向右分屏',exact=True).click();page.get_by_label('提交布局操作',exact=True).click()
    expect(page.get_by_label('关闭布局管理',exact=True)).not_to_be_visible()
    check('pane split uses the selected terminal and an explicit direction',state()['calls'][-1]['params']['direction']=='right' and state()['calls'][-1]['params']['target_pane_id']=='w4:p2')
    check('no uncaught browser errors',not errors)
    context.close();Path(page.video.path()).replace(out/'interaction.webm');browser.close()
(out/'verification.json').write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2))
print(f'Management/history verification: {len(checks)} checks passed; 0 uncaught errors.')
