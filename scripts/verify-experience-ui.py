def terminal(ws):
    def receive(data):
        frame=json.loads(data); frames.append(frame)
        if frame['type']=='auth':
            ws.send('{"type":"ready"}'); ws.send(b'\x1b[?1049h\x1b[?1000h\x1b[HOriginal terminal')
        if frame['type']=='ping': ws.send('{"type":"pong"}')
    ws.on_message(receive)
