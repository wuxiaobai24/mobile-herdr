"""Phone controls against an owned provider/socket and an isolated VT transport."""
import json, os, urllib.request
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

out = Path('artifacts/controls-ui')
checks, errors, frames, peers = [], [], [], []
def check(name, condition=True):
    assert condition, name
    checks.append(name)
def state():
    with urllib.request.urlopen(os.environ['MOBILE_HERDR_TEST_INSPECTOR'], timeout=5) as response:
        return json.load(response)
def snapshot(page, name):
    for browser_frame in page.frames:
        browser_frame.wait_for_function("() => document.getAnimations().filter(a=>a.effect.getComputedTiming().iterations!==Infinity).every(a=>a.playState!=='running')")
    page.screenshot(path=str(out / name))
def vt(ws):
    peers.append(ws)
    def receive(data):
        frame = json.loads(data); frames.append(frame)
        if frame['type'] == 'auth':
            ws.send('{"type":"ready"}')
            ws.send(b'\x1b[?2004hOriginal terminal\r\nTouch controls')
        if frame['type'] == 'ping': ws.send('{"type":"pong"}')
    ws.on_message(receive)
def inputs(): return [frame['data'] for frame in frames if frame['type'] == 'input']

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True, record_video_dir=str(out/'video'))
    context.grant_permissions(['clipboard-read','clipboard-write'], origin=os.environ['MOBILE_HERDR_TEST_URL'])
    page = context.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.route_web_socket('**/api/terminal', vt)
    page.goto(os.environ['MOBILE_HERDR_TEST_URL'])
    page.get_by_label('连接密钥', exact=True).fill(os.environ['MOBILE_HERDR_TEST_TOKEN'])
    page.get_by_label('连接开发机', exact=True).click()
    expect(page.get_by_label('在手机继续', exact=True)).to_be_visible()
    page.get_by_label('在手机继续', exact=True).click()
    expect(page.get_by_text('你正在手机上继续', exact=True)).to_be_visible()
    composer = page.get_by_label('发给原会话的消息', exact=True)
    composer.fill('/mo')
    expect(page.get_by_label('使用命令 /model', exact=True)).to_be_visible()
    page.get_by_label('使用命令 /model', exact=True).click()
    expect(page.get_by_label('使用模型 Fixture Fast', exact=True)).to_be_visible()
    page.get_by_label('使用模型 Fixture Fast', exact=True).click()
    expect(composer).to_have_value('')
    page.get_by_label('会话快捷选项', exact=True).click()
    expect(page.get_by_text('Fixture Fast', exact=True)).to_be_visible()
    check('slash autocomplete changes the live model with one selection', state()['model'] == 'fixture-fast')
    expect(page.get_by_label('选择思考强度', exact=True)).not_to_be_visible()
    check('a model without reasoning hides the reasoning shortcut')
    page.get_by_label('选择会话模型', exact=True).click()
    page.get_by_label('使用模型 Fixture Model', exact=True).click()
    composer.fill('/reasoning high'); page.get_by_label('发送消息', exact=True).click()
    expect(composer).to_have_value('')
    page.get_by_label('会话快捷选项', exact=True).click()
    expect(page.get_by_label('选择思考强度', exact=True)).to_contain_text('高')
    check('reasoning slash reaches the same provider and reports its value', state()['effort'] == 'high')
    snapshot(page, 'quick-options.png')
    page.get_by_label('选择思考强度', exact=True).click()
    snapshot(page, 'reasoning.png')
    page.get_by_label('使用思考强度 medium', exact=True).click()
    check('reasoning picker applies an advertised option', state()['effort'] == 'medium')
    composer.fill('/not-a-command'); page.get_by_label('发送消息', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('当前会话未提供')
    expect(composer).to_have_value('/not-a-command')
    check('unknown slash stays a draft and never becomes an agent prompt', state()['slashPrompts'] == 0)
    composer.fill('长草稿\n第二行\n第三行')
    page.get_by_label('会话快捷选项', exact=True).click(); page.get_by_label('命令 /editor', exact=True).click()
    expect(page.get_by_test_id('expanded-composer')).to_be_visible()
    expect(composer).to_have_value('长草稿\n第二行\n第三行')
    check('fullscreen and inline edit exactly one shared draft', composer.count() == 1)
    for width,height in [(320,568),(390,450),(844,390)]:
        page.set_viewport_size({'width':width,'height':height})
        page.wait_for_function("""(height)=>Math.abs(document.querySelector('[data-testid="expanded-composer"]').getBoundingClientRect().height-height)<2""", arg=height)
        page.wait_for_function("() => document.getAnimations().filter(a=>a.effect.getComputedTiming().iterations!==Infinity).every(a=>a.playState!=='running')")
        expect(page.get_by_label('收起消息编辑器', exact=True)).to_be_visible()
        box = page.get_by_label('发送消息', exact=True).bounding_box()
        if box['y']+box['height'] > height+1:
            snapshot(page, 'fullscreen-overflow.png')
            print('Fullscreen layout:', page.get_by_test_id('expanded-composer').evaluate("el=>[el,...el.children].map(x=>({tag:x.tagName,rect:x.getBoundingClientRect().toJSON(),flex:getComputedStyle(x).flex,height:getComputedStyle(x).height}))"), flush=True)
        check(f'{width}x{height}: fullscreen send remains reachable', box['y']+box['height'] <= height+1)
        check(f'{width}x{height}: fullscreen has no horizontal overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    page.set_viewport_size({'width':390,'height':844})
    snapshot(page, 'fullscreen-draft.png')
    page.evaluate("""() => { window.savedSetItem=Storage.prototype.setItem; Storage.prototype.setItem=function(k,v){if(k.startsWith('mobile-herdr-draft:'))throw Error('fixture quota');return window.savedSetItem.call(this,k,v);}; }""")
    composer.fill('保存失败仍保留的长草稿')
    expect(page.get_by_test_id('expanded-composer')).to_contain_text('草稿未保存')
    check('fullscreen reports a failed save and keeps editable text', composer.input_value() == '保存失败仍保留的长草稿')
    page.evaluate('() => { Storage.prototype.setItem=window.savedSetItem; }')
    composer.fill('Controls durable draft')
    expect(page.get_by_test_id('expanded-composer')).to_contain_text('草稿已保存')
    page.get_by_label('收起消息编辑器', exact=True).click(); page.reload()
    expect(composer).to_have_value('Controls durable draft')
    check('collapsed fullscreen draft survives reload')
    composer.fill('Controls native message')
    page.route('**/api/panes/*/native?*', lambda route: route.abort('failed') if route.request.method == 'POST' and route.request.post_data_json.get('action') == 'prompt' else route.continue_())
    page.get_by_label('发送消息', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('操作可能已经送达')
    expect(composer).to_have_value('Controls native message')
    page.unroute('**/api/panes/*/native?*')
    check('failed delivery keeps the draft and does not auto replay', state()['sent'] == 0)
    page.get_by_label('发送消息', exact=True).click()
    expect(composer).to_have_value('')
    expect(page.get_by_label('中断 agent', exact=True)).to_be_visible()
    check('explicit retry reaches the original native runtime once', state()['sent'] == 1)
    composer.fill('/stop'); page.get_by_label('发送消息', exact=True).click()
    expect(composer).to_have_value('')
    expect(page.get_by_label('中断 agent', exact=True)).not_to_be_visible()
    check('stop slash interrupts the existing turn', state()['status'] == 'idle')
    page.get_by_label('复制回复', exact=True).last.click()
    check('reply copy uses the actual answer', '已收到：Controls native message' in page.evaluate('navigator.clipboard.readText()'))
    page.get_by_label('更多会话操作', exact=True).click(); page.get_by_label('查找与历史', exact=True).click()
    search = page.get_by_label('查找当前对话', exact=True)
    search.fill('no-match-fixture')
    expect(page.get_by_test_id('conversation-match-count')).to_have_text('没有匹配')
    expect(page.get_by_label('下一个匹配', exact=True)).to_be_disabled()
    page.get_by_label('清空对话查找', exact=True).click()
    expect(search).to_have_value('')
    check('search distinguishes an empty query and no results')
    snapshot(page, 'phone-search.png')
    page.get_by_label('关闭对话查找', exact=True).click()
    page.get_by_role('tab', name='终端', exact=True).click()
    frame = page.frame_locator('iframe[title="原始 Herdr 终端"]')
    expect(frame.locator('#state')).to_contain_text('实时终端')
    frame.get_by_label('打开终端键盘', exact=True).click()
    frame.get_by_label('一次性 Ctrl', exact=True).click(); page.keyboard.type('c')
    expect(frame.get_by_label('一次性 Ctrl', exact=True)).to_have_attribute('aria-pressed', 'false')
    check('Ctrl applies to one keyboard input', inputs()[-1] == '\x03')
    frame.get_by_label('一次性 Alt', exact=True).click(); page.keyboard.type('b')
    check('Alt sends an actual escape-prefixed key', inputs()[-1] == '\x1bb')
    frame.get_by_label('打开方向面板', exact=True).click()
    frame.get_by_label('终端向左', exact=True).click()
    check('floating directions dispatch real terminal sequences', inputs()[-1] == '\x1b[D')
    before = len(inputs())
    handle = frame.locator('#pad-handle').bounding_box()
    page.mouse.move(handle['x']+20,handle['y']+15); page.mouse.down(); page.mouse.move(handle['x']-60,handle['y']-40,steps=5); page.mouse.up()
    check('dragging the direction pad sends no input', len(inputs()) == before)
    for width,height in [(320,568),(390,450),(844,390)]:
        page.set_viewport_size({'width':width,'height':height})
        expect(frame.get_by_label('打开终端键盘', exact=True)).to_be_visible()
        check(f'{width}x{height}: fixed terminal tools stay on screen', frame.locator('body').evaluate('el=>el.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':390,'height':844})
    snapshot(page, 'terminal-directions.png')
    frame.get_by_label('关闭方向面板', exact=True).click()
    page.evaluate("navigator.clipboard.writeText('printf preview')")
    before = len(inputs())
    frame.get_by_label('预览终端粘贴', exact=True).click()
    expect(frame.get_by_label('待粘贴的终端内容', exact=True)).to_have_value('printf preview')
    check('opening paste only previews clipboard text', len(inputs()) == before)
    snapshot(page, 'terminal-paste.png')
    frame.get_by_role('button', name='粘贴到终端', exact=True).click()
    check('explicit paste honors bracketed-paste mode', inputs()[-1] == '\x1b[200~printf preview\x1b[201~')
    frame.get_by_label('预览终端粘贴', exact=True).click()
    frame.get_by_label('待粘贴的终端内容', exact=True).fill('offline paste draft')
    before = len(inputs())
    peers[-1].send('{"type":"control","writable":false,"message":"当前终端只读"}')
    expect(frame.get_by_role('button', name='粘贴到终端', exact=True)).to_be_disabled()
    expect(frame.get_by_label('一次性 Ctrl', exact=True)).to_be_disabled()
    peers[-1].send('{"type":"control","writable":true}')
    expect(frame.get_by_role('button', name='粘贴到终端', exact=True)).to_be_enabled()
    expect(frame.get_by_label('待粘贴的终端内容', exact=True)).to_have_value('offline paste draft')
    check('ownership loss preserves paste and restores without replay', len(inputs()) == before)
    frame.get_by_label('关闭终端粘贴', exact=True).click()
    frame.get_by_role('button', name='历史', exact=True).click()
    check('history browsing sends zero terminal input', len(inputs()) == before)
    check('no uncaught browser errors', not errors)
    context.close(); Path(page.video.path()).replace(out/'interaction.webm'); browser.close()
(out/'verification.json').write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2))
print(f'Mobile controls verification: {len(checks)} checks passed; 0 uncaught errors.')
