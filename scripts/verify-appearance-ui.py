"""Theme settings and terminal gestures against owned fixtures and a simulated VT stream."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

out = Path('artifacts/appearance-ui')
checks, errors, frames = [], [], []
terminal_peer = [None]
def check(name, condition=True):
    assert condition, name
    checks.append(name)
def snapshot(page, name):
    page.wait_for_function("() => document.getAnimations().filter(a => a.effect.getComputedTiming().iterations !== Infinity).every(a => a.playState !== 'running')")
    page.screenshot(path=str(out / name))
def vt_stream(ws):
    terminal_peer[0] = ws
    def message(data):
        frame = json.loads(data)
        frames.append(frame)
        if frame['type'] == 'ping': ws.send(json.dumps({'type':'pong'}))
        if frame['type'] == 'auth':
            ws.send(json.dumps({'type': 'ready'}))
            ws.send(b'\x1b[?1049h\x1b[?1000h\x1b[?1006h\x1b[HFull-screen terminal\r\nSwipe to browse history')
    ws.on_message(message)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True, record_video_dir=str(out/'video'))
    page = context.new_page()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.route_web_socket('**/api/terminal', vt_stream)
    page.goto(os.environ['MOBILE_HERDR_TEST_URL'])
    page.get_by_label('连接密钥', exact=True).fill(os.environ['MOBILE_HERDR_TEST_TOKEN'])
    page.get_by_label('连接开发机', exact=True).click()
    expect(page.get_by_label('发给原会话的消息', exact=True)).to_be_visible()
    page.get_by_label('发给原会话的消息', exact=True).fill('切换主题时保留草稿')
    expect(page.get_by_text('草稿已保存', exact=True)).to_be_visible()
    snapshot(page, 'mocha-chat.png')
    page.get_by_label('外观设置', exact=True).click()
    snapshot(page, 'theme-settings.png')
    for id, name, bg in [('latte','Catppuccin Latte','#eff1f5'), ('macchiato','Catppuccin Macchiato','#24273a'), ('frappe','Catppuccin Frappé','#303446'), ('flexoki-dark','Flexoki Dark','#100f0f'), ('flexoki-light','Flexoki Light','#fffcf0'), ('mocha','Catppuccin Mocha','#1e1e2e')]:
        page.get_by_role('radio', name=name, exact=True).click()
        expect(page.locator('html')).to_have_attribute('data-theme', id)
        check(name + ' updates the live palette', page.evaluate('getComputedStyle(document.documentElement).getPropertyValue("--bg").trim()') == bg)
    page.get_by_label('增大阅读字号', exact=True).click()
    page.get_by_label('增大阅读字号', exact=True).click()
    expect(page.get_by_label('增大阅读字号', exact=True)).to_be_disabled()
    page.get_by_label('增大终端字号', exact=True).click()
    page.get_by_label('等宽字体', exact=True).click()
    expect(page.get_by_test_id('reading-preview')).to_have_css('font-size', '20px')
    page.get_by_role('radio', name='Flexoki Light', exact=True).click()
    snapshot(page, 'flexoki-settings.png')
    page.set_viewport_size({'width':320,'height':568})
    page.get_by_test_id('reading-preview').scroll_into_view_if_needed()
    expect(page.get_by_test_id('reading-preview')).to_have_css('font-size','20px')
    check('320px: large-font appearance panel scrolls to all controls', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    page.get_by_label('关闭外观设置', exact=True).scroll_into_view_if_needed()
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_label('关闭外观设置', exact=True).click()
    expect(page.locator('.markdown').first).to_have_css('font-size', '20px')
    check('reading size and font affect content and preview', 'mono' in page.locator('.markdown').first.evaluate('el => getComputedStyle(el).fontFamily').lower())
    snapshot(page, 'flexoki-large-chat.png')
    page.set_viewport_size({'width':1280,'height':900})
    snapshot(page, 'desktop-flexoki-chat.png')
    page.set_viewport_size({'width':390,'height':844})
    page.reload()
    expect(page.locator('html')).to_have_attribute('data-theme', 'flexoki-light')
    expect(page.locator('.markdown').first).to_have_css('font-size', '20px')
    expect(page.get_by_label('发给原会话的消息', exact=True)).to_have_value('切换主题时保留草稿')
    check('theme, typography and the pane draft survive reload')
    page.get_by_label('外观设置', exact=True).click()
    # A real storage failure must be visible without undoing the live preview.
    page.evaluate("""() => { window.originalSet = Storage.prototype.setItem; Storage.prototype.setItem = function(k,v) { if(k.endsWith(':appearance')) throw new Error('fixture storage failure'); return window.originalSet.call(this,k,v); }; }""")
    page.get_by_role('radio', name='Catppuccin Latte', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('设置未能保存')
    expect(page.locator('html')).to_have_attribute('data-theme', 'latte')
    check('failed settings save stays visible and preserves the live preview')
    page.evaluate('() => { Storage.prototype.setItem = window.originalSet; delete window.originalSet; }')
    page.get_by_role('radio', name='Catppuccin Mocha', exact=True).click()
    page.get_by_label('减小阅读字号', exact=True).click()
    page.get_by_label('减小阅读字号', exact=True).click()
    page.get_by_label('系统字体', exact=True).click()
    page.get_by_label('关闭外观设置', exact=True).click()
    page.get_by_role('tab', name='终端', exact=True).click()
    frame = page.frame_locator('iframe[title="原始 Herdr 终端"]')
    expect(frame.locator('#state')).to_contain_text('实时终端')
    expect(frame.locator('html')).to_have_attribute('data-theme', 'mocha')
    check('terminal receives the parent theme and independent font size', frame.locator('html').evaluate('el => el.style.getPropertyValue("--terminal-size")') == '15px')
    # Alternate screen and mouse reporting must never turn scroll gestures into input.
    frame.locator('#terminal').hover()
    page.mouse.wheel(0, -300)
    expect(frame.locator('#history')).to_be_visible()
    expect(frame.locator('#history-content')).to_contain_text('history-001')
    content = frame.locator('#history-content')
    expect(content).to_contain_text('history-400')
    content.evaluate('el => el.scrollTop = el.scrollHeight')
    before = content.evaluate('el => el.scrollTop')
    content.hover(); page.mouse.wheel(0, -400)
    page.wait_for_function("() => { const el=document.querySelector('iframe').contentDocument.getElementById('history-content'); return el.scrollTop < el.scrollHeight-el.clientHeight-100; }")
    check('full-screen history really scrolls and is selectable', content.evaluate('el => getComputedStyle(el).userSelect') == 'text' and content.evaluate('el => el.scrollTop') < before)
    snapshot(page, 'terminal-history.png')
    old = content.evaluate('el => el.scrollTop')
    frame.get_by_text('刷新', exact=True).click()
    expect(frame.locator('#history-note')).to_contain_text('终端历史')
    check('history supports horizontal scrolling for long terminal lines', content.evaluate('el => { el.scrollLeft=100; return el.scrollLeft > 0; }'))
    check('refreshing history retains the reading position', abs(content.evaluate('el => el.scrollTop') - old) < 2)
    frame.get_by_text('返回终端', exact=True).click()
    # CDP touch events run Chromium's real event dispatch, rather than a DOM-only touch mock.
    box = page.locator('iframe').bounding_box()
    cdp = context.new_cdp_session(page)
    x, y = box['x']+150, box['y']+130
    cdp.send('Input.dispatchTouchEvent', {'type':'touchStart','touchPoints':[{'x':x,'y':y}]})
    cdp.send('Input.dispatchTouchEvent', {'type':'touchMove','touchPoints':[{'x':x,'y':y+100}]})
    cdp.send('Input.dispatchTouchEvent', {'type':'touchEnd','touchPoints':[]})
    expect(frame.locator('#history')).to_be_visible()
    check('touch drag opens scrollable history from an alternate-screen app')
    check('scroll and touch emit zero input frames', not any(f['type']=='input' for f in frames))
    frame.get_by_text('返回终端', exact=True).click()
    # Normal output has native xterm scrollback; scrolling must keep subsequent output offscreen.
    terminal_peer[0].send(b'\x1b[?1049l\x1b[?1000l\x1b[?1006l' + ''.join(f'normal-{i:03d}\r\n' for i in range(180)).encode())
    frame.locator('#terminal').hover(); page.mouse.wheel(0, -200)
    expect(frame.locator('#latest')).to_be_visible()
    terminal_peer[0].send(b'new output while reading\r\n')
    expect(frame.locator('#latest')).to_be_visible()
    check('normal scrollback stays in place while output arrives')
    snapshot(page, 'terminal-scrollback.png')
    frame.locator('#latest').click()
    expect(frame.locator('#latest')).not_to_be_visible()
    check('return-to-live restores terminal follow')
    auth_before = len([f for f in frames if f['type']=='auth'])
    page.get_by_label('外观设置', exact=True).click()
    page.get_by_role('radio', name='Flexoki Light', exact=True).click()
    page.get_by_label('增大终端字号', exact=True).click()
    page.get_by_label('关闭外观设置', exact=True).click()
    expect(frame.locator('html')).to_have_attribute('data-theme','flexoki-light')
    check('theme/font update does not detach or reconnect the terminal', len([f for f in frames if f['type']=='auth']) == auth_before)
    check('font update reaches the existing terminal', frame.locator('html').evaluate('el => el.style.getPropertyValue("--terminal-size")') == '17px')
    snapshot(page, 'flexoki-terminal.png')
    frame.get_by_text('历史', exact=True).click()
    for width,height in [(320,568),(390,450),(844,390)]:
        page.set_viewport_size({'width':width,'height':height})
        expect(frame.locator('#history-content')).to_be_visible()
        frame.locator('#history-content').evaluate('el => el.scrollTop=0')
        expect(frame.locator('#history-content')).to_contain_text('history-001')
        check(f'{width}x{height}: history remains scrollable without page overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    check('browsing history never writes to the pane', not any(f['type']=='input' for f in frames))
    page.set_viewport_size({'width':390,'height':844})
    snapshot(page, 'flexoki-terminal-history.png')
    check('no uncaught browser errors', not errors)
    context.close(); Path(page.video.path()).replace(out/'interaction.webm'); browser.close()
(out/'verification.json').write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2))
print(f'Appearance/terminal verification: {len(checks)} checks passed; 0 uncaught errors.')
